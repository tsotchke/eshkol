#!/usr/bin/env bash
# Regenerate lib/backend/gpu/vulkan_spirv.h from lib/backend/gpu/vulkan/*.comp.
#
# The Vulkan compute backend embeds its kernels as SPIR-V words so that a build
# host needs no shader compiler. This script is the only producer of that
# header: it compiles every GLSL compute shader with glslc (shaderc) for the
# Vulkan 1.0 environment and writes one uint32_t array per kernel.
#
# Usage:
#   scripts/gen_vulkan_spirv.sh           rewrite the header
#   scripts/gen_vulkan_spirv.sh --check   regenerate into scratch and compare
#
# GLSLC selects the compiler (default: glslc on PATH, then the Homebrew
# shaderc keg). Output is deterministic for a given glslc version, which the
# header records.
set -euo pipefail

root="$(cd "$(dirname "$0")/.." && pwd)"
src_dir="$root/lib/backend/gpu/vulkan"
header="$root/lib/backend/gpu/vulkan_spirv.h"
mode="${1:-write}"

glslc="${GLSLC:-}"
if [ -z "$glslc" ]; then
    if command -v glslc >/dev/null 2>&1; then
        glslc="$(command -v glslc)"
    else
        for cand in /opt/homebrew/opt/shaderc/bin/glslc /opt/homebrew/Cellar/shaderc/*/bin/glslc \
                    /usr/local/opt/shaderc/bin/glslc; do
            if [ -x "$cand" ]; then glslc="$cand"; break; fi
        done
    fi
fi
if [ -z "$glslc" ] || [ ! -x "$glslc" ]; then
    echo "SKIP: glslc not found (set GLSLC=/path/to/glslc)" >&2
    exit 77
fi

work="${ESHKOL_VK_SPIRV_WORKDIR:-$root/.scratch/vulkan-spirv-gen}"
mkdir -p "$work"
version="$("$glslc" --version 2>&1 | sed -n 1p | tr -d '\r')"

for comp in "$src_dir"/*.comp; do
    name="$(basename "$comp" .comp)"
    "$glslc" --target-env=vulkan1.0 -O0 -fshader-stage=compute \
        -o "$work/$name.spv" "$comp"
done

out="$work/vulkan_spirv.h"
python3 - "$src_dir" "$work" "$out" "$version" <<'PY'
import os, struct, sys
src_dir, work, out, version = sys.argv[1:5]
names = sorted(f[:-5] for f in os.listdir(src_dir) if f.endswith('.comp'))
lines = [
    "/*",
    " * vulkan_spirv.h - SPIR-V for the Vulkan compute backend (gpu_vulkan.c).",
    " *",
    " * GENERATED by scripts/gen_vulkan_spirv.sh from the .comp sources in lib/backend/gpu/vulkan/",
    " * with %s (--target-env=vulkan1.0 -O0)." % version,
    " * Do not edit; edit the .comp sources and rerun the script.",
    " * Verify with: scripts/gen_vulkan_spirv.sh --check",
    " *",
    " * Copyright (C) tsotchke",
    " * SPDX-License-Identifier: MIT",
    " */",
    "#ifndef ESHKOL_VULKAN_SPIRV_H",
    "#define ESHKOL_VULKAN_SPIRV_H",
    "",
    "#include <stddef.h>",
    "#include <stdint.h>",
    "",
]
for name in names:
    data = open(os.path.join(work, name + '.spv'), 'rb').read()
    assert len(data) % 4 == 0
    words = struct.unpack('<%dI' % (len(data) // 4), data)
    assert words[0] == 0x07230203, name
    lines.append("static const uint32_t eshkol_vk_spirv_%s[%d] = {" % (name, len(words)))
    for i in range(0, len(words), 6):
        lines.append("    " + ", ".join("0x%08xu" % w for w in words[i:i + 6]) + ",")
    lines.append("};")
    lines.append("static const size_t eshkol_vk_spirv_%s_size = sizeof(eshkol_vk_spirv_%s);" % (name, name))
    lines.append("")
lines.append("#endif /* ESHKOL_VULKAN_SPIRV_H */")
open(out, 'w').write("\n".join(lines) + "\n")
PY

if [ "$mode" = "--check" ]; then
    if cmp -s "$out" "$header"; then
        echo "PASS: $header is current"
        exit 0
    fi
    echo "FAIL: $header is not what scripts/gen_vulkan_spirv.sh produces"
    diff "$header" "$out" | head -40 || true
    exit 1
fi
cp "$out" "$header"
echo "wrote $header"
