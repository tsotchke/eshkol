#!/usr/bin/env python3
"""Generate source-bound VM read identities; no runtime execution credit."""
import argparse, json
from pathlib import Path
import gen_language_surface as surface
ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "lib/backend/vm_binding_origins.h"
def fnv(data, bits):
    value, prime = (2166136261, 16777619) if bits == 32 else (14695981039346656037, 1099511628211)
    for byte in data:
        value = ((value ^ byte) * prime) & ((1 << bits) - 1)
    return value & 0x7fffffff if bits == 32 else value

def render():
    data = surface.extract_stdlib_surface(str(ROOT))
    origins = {}
    hashes = {}
    for records in list(data["closure_names"].values()) + list(data["names"].values()):
        for record in records:
            origin = record.get("resolved_binding_origin")
            identity = record.get("binding_identity")
            if not origin or not identity:
                continue
            key = (origin["module"], origin["path"], origin["name"], origin["line"])
            marker = fnv(identity.encode(), 32)
            if not marker or marker in hashes and hashes[marker] != identity:
                raise ValueError("ambiguous binding identity hash")
            hashes[marker] = identity
            origins[key] = marker
    lines = ["/* Generated by scripts/gen_vm_binding_origins.py; do not edit. */",
             "#ifndef ESHKOL_VM_BINDING_ORIGINS_H", "#define ESHKOL_VM_BINDING_ORIGINS_H",
             "typedef struct { const char *module, *name; int line; uint32_t id; uint64_t source_hash; } VmBindingOrigin;",
             "static const VmBindingOrigin vm_binding_origins[] = {"]
    for (module, path, name, line), marker in sorted(origins.items()):
        source_hash = fnv((ROOT / path).read_bytes(), 64)
        lines.append("    {%s, %s, %d, UINT32_C(%d), UINT64_C(%d)}," %
                     (json.dumps(module), json.dumps(name), line, marker, source_hash))
    lines += ["};", "#endif", ""]
    return "\n".join(lines)
if __name__ == "__main__":
    parser = argparse.ArgumentParser(); parser.add_argument("--check", action="store_true")
    args = parser.parse_args(); content = render()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != content:
            raise SystemExit("VM binding origins are stale")
    else:
        OUTPUT.write_text(content)
