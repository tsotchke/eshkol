#!/usr/bin/env python3
"""Generate the product WASM's small, deterministic core module registry."""

from __future__ import annotations

import argparse
import hashlib
from pathlib import Path
import sys


MODULES = (
    ("core.msgpack", "lib/core/msgpack.esk"),
    ("core.testing", "lib/core/testing.esk"),
    ("core.list.query", "lib/core/list/query.esk"),
    ("core.list.transform", "lib/core/list/transform.esk"),
)


def c_string(data: bytes) -> str:
    # Three-digit octal escapes cannot consume a following hex digit.
    return '"' + "".join(f"\\{byte:03o}" for byte in data) + '"'


def render(root: Path) -> bytes:
    lines = [
        "/* Generated by scripts/generate_wasm_embedded_modules.py; do not edit. */",
        "#ifndef ESHKOL_VM_EMBEDDED_MODULES_H",
        "#define ESHKOL_VM_EMBEDDED_MODULES_H",
        "#include <stddef.h>",
        "#include <stdio.h>",
        "#include <string.h>",
        "typedef struct { const char* name; const char* path; const char* source; } VmEmbeddedModule;",
    ]
    entries = []
    for index, (name, relpath) in enumerate(MODULES):
        data = (root / relpath).read_bytes()
        data.decode("utf-8")
        if b"\0" in data:
            raise ValueError(f"NUL byte in embedded source: {relpath}")
        digest = hashlib.sha256(data).hexdigest()
        lines.append(f"/* sha256 {name} {digest} */")
        lines.append(f"static const char vm_embedded_source_{index}[] =")
        lines.extend("    " + c_string(data[i : i + 72]) for i in range(0, len(data), 72))
        lines[-1] += ";"
        entries.append(
            f'    {{"{name}", "/__eshkol_embedded__/{name}.esk", vm_embedded_source_{index}}}'
        )
    lines.extend(
        [
            "static const VmEmbeddedModule vm_embedded_modules[] = {",
            ",\n".join(entries),
            "};",
            "static int vm_embedded_module_lookup(const char* name, const char** source,",
            "                                     char* path, size_t path_capacity) {",
            "    for (size_t i = 0; i < sizeof(vm_embedded_modules) / sizeof(vm_embedded_modules[0]); ++i) {",
            "        const VmEmbeddedModule* module = &vm_embedded_modules[i];",
            "        if (strcmp(name, module->name) != 0) continue;",
            "        if (strlen(module->path) + 1 > path_capacity) return 0;",
            "        memcpy(path, module->path, strlen(module->path) + 1);",
            "        *source = module->source;",
            "        return 1;",
            "    }",
            "    return 0;",
            "}",
            "#endif",
            "",
        ]
    )
    return "\n".join(lines).encode("ascii")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--check", action="store_true", help="fail if output differs from current sources")
    args = parser.parse_args()
    expected = render(args.root.resolve())
    if args.check:
        try:
            actual = args.output.read_bytes()
        except OSError as exc:
            print(f"missing generated header: {args.output}: {exc}", file=sys.stderr)
            return 1
        if actual != expected:
            print(f"generated header drift: {args.output}", file=sys.stderr)
            return 1
        print(f"embedded module header matches {len(MODULES)} sources")
        return 0
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_bytes(expected)
    print(f"generated {args.output} from {len(MODULES)} module sources")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
