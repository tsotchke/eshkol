def build_overrides():
    overrides = {}

    for name, extra in _NUMERIC_NOT_DEVICE_REPRESENTABLE.items():
        overrides[name] = (HOST, extra)

    for name, extra in _GEOMETRY_HANDLE_LIFECYCLE.items():
        overrides[name] = (HOST, extra)

    for name, (label, rationale) in _VECTOR_OVERRIDES.items():
        overrides[name] = (label, rationale)

    for name, extra in _HIGHER_ORDER_HOST_ONLY.items():
        overrides[name] = (HOST, extra)

    for name, extra in _PREDICATE_NUMERIC_SCALAR.items():
        overrides[name] = (DEVICE, extra)

    for name, (label, rationale) in _CONTROL_FLOW_NOT.items():
        overrides[name] = (label, rationale)

    for name, (label, rationale) in _MISC_NUMERIC_DUPLICATES.items():
        overrides[name] = (label, rationale)

    for name, extra in _TENSOR_AD_HOST.items():
        overrides[name] = (HOST, extra)

    for name, extra in _TENSOR_AD_HDI.items():
        overrides[name] = (HDI, extra, _HDI_INNER_OP)

    return overrides


def classify(builtin, overrides):
    name = builtin["name"]
    category = builtin["category"]

    if name in overrides:
        entry = overrides[name]
        if len(entry) == 3:
            label, rationale, inner_op = entry
        else:
            label, rationale = entry
            inner_op = None
        return label, rationale, inner_op

    label = CATEGORY_DEFAULT.get(category)
    if label is None:
        return None, None, None

    rationale = CATEGORY_RATIONALE.get((category, label))
    if rationale is None:
        rationale = f"Category '{category}' defaults to {label}; see " \
            "docs/design/ESHKOL_S_FRAGMENT.md."

    inner_op = _HDI_INNER_OP if label == HDI else None
    return label, rationale, inner_op


def yaml_escape(text):
    text = text.replace("\\", "\\\\").replace('"', '\\"')
    return f'"{text}"'


def yaml_key(name):
    # Builtin names contain characters (?, !, +, <, ->, ...) that are not
    # bare YAML scalars; always double-quote keys for a parser-agnostic file.
    escaped = name.replace("\\", "\\\\").replace('"', '\\"')
    return f'"{escaped}"'


def render_yaml(entries, surface_path, meta):
    lines = []
    lines.append("# lib/backend/xla/builtin_classification.yaml")
    lines.append("#")
    lines.append("# Generated by scripts/gen_builtin_classification.py — do not hand-edit.")
    lines.append("# Regenerate with:")
    lines.append("#   python3 scripts/gen_builtin_classification.py")
    lines.append("#")
    lines.append("# Every builtin the compiler registers (per")
    lines.append(f"# {os.path.relpath(surface_path, REPO)}'s builtins[] array, itself derived")
    lines.append("# from lib/backend/eshkol_compiler.c BUILTINS[], lib/backend/eshkol_vm.c")
    lines.append("# BUILTINS[], and the quantum/PQC agent-module surface — see")
    lines.append("# scripts/gen_language_surface.py) gets exactly one of the three labels")
    lines.append("# docs/design/ESHKOL_S_FRAGMENT.md defines: device, host,")
    lines.append("# host-with-device-inner. scripts/check_builtin_classification.py enforces")
    lines.append("# that this file and the registry agree exactly.")
    lines.append("version: 1")
    lines.append(f"source_registry: {os.path.relpath(surface_path, REPO)}")
    lines.append("generator: scripts/gen_builtin_classification.py")
    lines.append("labels: [device, host, host-with-device-inner]")
    lines.append(f"builtin_count: {meta['count']}")
    lines.append("counts_by_label:")
    for label in (DEVICE, HOST, HDI):
        lines.append(f"  {label}: {meta['by_label'][label]}")
    lines.append("builtins:")
    for name, label, rationale, inner_op in entries:
        lines.append(f"  {yaml_key(name)}:")
        lines.append(f"    label: {label}")
        lines.append(f"    rationale: {yaml_escape(rationale)}")
        if inner_op:
            lines.append(f"    inner_op: {yaml_escape(inner_op)}")
    lines.append("")
    return "\n".join(lines)


def main(argv):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--surface", default=DEFAULT_SURFACE)
    parser.add_argument("--out", default=DEFAULT_OUT)
    args = parser.parse_args(argv)

    with open(args.surface, encoding="utf-8") as fh:
        surface = json.load(fh)

    builtins = surface["builtins"]
    overrides = build_overrides()

    entries = []
    unclassifiable = []
    by_label = {DEVICE: 0, HOST: 0, HDI: 0}
    seen = set()
    for b in sorted(builtins, key=lambda x: x["name"]):
        name = b["name"]
        if name in seen:
            continue
        seen.add(name)
        label, rationale, inner_op = classify(b, overrides)
        if label is None:
            unclassifiable.append((name, b["category"]))
            continue
        by_label[label] += 1
        entries.append((name, label, rationale, inner_op))

    if unclassifiable:
        sys.stderr.write(
            "gen_builtin_classification.py: no category default for "
            f"{len(unclassifiable)} builtin(s):\n"
        )
        for name, category in unclassifiable:
            sys.stderr.write(f"  {name!r} (category={category!r})\n")
        return 1

    # Every declared override must have matched a real builtin, or the
    # override table has drifted from the registry (a rename, a removal).
    all_names = {b["name"] for b in builtins}
    stale_overrides = sorted(set(overrides) - all_names)
    if stale_overrides:
        sys.stderr.write(
            "gen_builtin_classification.py: overrides reference builtins "
            f"not present in {args.surface}:\n"
        )
        for name in stale_overrides:
            sys.stderr.write(f"  {name!r}\n")
        return 1

    meta = {"count": len(entries), "by_label": by_label}
    out_text = render_yaml(entries, args.surface, meta)

    os.makedirs(os.path.dirname(args.out), exist_ok=True)
    with open(args.out, "w", encoding="utf-8") as fh:
        fh.write(out_text)

    print(f"Wrote {args.out}")
    print(f"  {meta['count']} builtins classified: "
          f"device={by_label[DEVICE]} host={by_label[HOST]} "
          f"host-with-device-inner={by_label[HDI]}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
