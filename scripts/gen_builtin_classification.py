#!/usr/bin/env python3
"""gen_builtin_classification.py — derive lib/backend/xla/builtin_classification.yaml
from the compiler's real builtin registry.

This is the "never by hand" mechanism the Eshkol-S contract
(docs/design/ESHKOL_S_FRAGMENT.md, "Three labels for every builtin") calls
for: it does not invent a builtin list, it reads tests/coverage/language_surface.json
(itself generated by scripts/gen_language_surface.py directly from the
compiler/VM source — lib/backend/eshkol_compiler.c BUILTINS[], lib/backend/
eshkol_vm.c BUILTINS[], and the small quantum/PQC agent-module surface) and
assigns each of the builtins it finds exactly one of the three labels the
contract defines: device, host, host-with-device-inner.

Classification method: every builtin inherits a default label from its
language_surface.json category (CATEGORY_DEFAULT below), then a curated,
per-name override table (OVERRIDES) corrects the entries where the category
default is wrong for that specific builtin — the tape-facing half of
tensor_ad versus its pure-tensor half is the largest such split; see the
category notes inline. Every override carries its own rationale text
distinct from the category template, because an override is exactly the
judgment call this file exists to make explicit and reviewable.

Re-run this script whenever the registry changes (a builtin is added,
renamed, or removed) and re-review the diff — it is expected to require a
human decision for any newly-added builtin that does not fit an existing
category cleanly, which is why this is a checked-in generator rather than a
one-shot script: scripts/check_builtin_classification.py fails the gate the
moment the registry and the committed YAML disagree, and regenerating is
the first step of resolving that failure (followed by reviewing any name
gen_builtin_classification.py could not place confidently).

Usage:
  python3 scripts/gen_builtin_classification.py
      [--surface tests/coverage/language_surface.json]
      [--out lib/backend/xla/builtin_classification.yaml]
"""

