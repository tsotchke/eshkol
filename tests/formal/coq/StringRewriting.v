(* ------------------------------------------------------------------------
   String rewriting: what core.category.presented relies on.

   core.category.presented (ADR-0054) decides equality of composites in a
   finitely presented category by Knuth-Bendix completion of the relations
   under the shortlex order. Its answers are justified by the theorems
   below, stated for words over any alphabet:

     newman                 a terminating, locally confluent relation is
                            confluent (Newman 1942);
     unique_normal_forms    under a confluent relation two normal forms of
                            one word are equal;
     step_sound, star_sound every rewrite step (and every sequence of steps)
                            relates congruent words, as long as every rule is
                            a consequence of the relations;
     completion_sound       every state reached by completion (orienting an
                            equation after reducing it, adding a critical
                            pair, simplifying a right-hand side, returning a
                            rule to the pending equations, dropping a joined
                            equation) keeps all rules and equations inside
                            the congruence: an 'equal answer is always sound,
                            complete or not;
     decide_by_normal_forms with a confluent rule set whose rules are
                            consequences of the relations and which joins
                            every relation, two words are congruent exactly
                            when their normal forms coincide: a complete
                            system's 'distinct answer is always sound.

   Words of a category are paths (composable generator sequences); a rule
   relates parallel paths, so a rewrite inside a path yields a path and every
   derivation that starts from a path stays among paths. The congruence on
   paths is therefore the restriction of the congruence on words proved
   about here.
   ------------------------------------------------------------------------ *)

From Stdlib Require Import List Relations.
Import ListNotations.

Section Abstract.
  Variable A : Type.
  Variable R : A -> A -> Prop.

  Inductive star : A -> A -> Prop :=
  | star_refl : forall x, star x x
  | star_step : forall x y z, R x y -> star y z -> star x z.

  Lemma star_trans : forall x y z, star x y -> star y z -> star x z.
  Proof.
    intros x y z H; revert z; induction H; intros; auto.
    eapply star_step; eauto.
  Qed.

  Definition joinable (y z : A) : Prop := exists w, star y w /\ star z w.
  Definition locally_confluent : Prop :=
    forall x y z, R x y -> R x z -> joinable y z.
  Definition confluent : Prop :=
    forall x y z, star x y -> star x z -> joinable y z.
  (* termination: no infinite chain x0 -> x1 -> ..., i.e. the converse of R
     is well founded *)
  Definition terminating : Prop := well_founded (fun y x => R x y).
  Definition normal (x : A) : Prop := forall y, ~ R x y.

  Theorem newman : terminating -> locally_confluent -> confluent.
  Proof.
    intros Hwf Hlc x.
    induction x as [x IH] using (well_founded_ind Hwf).
    intros y z Hy Hz.
    destruct Hy as [x | x y1 y Hxy1 Hy1y].
    - exists z; split; [exact Hz | apply star_refl].
    - destruct Hz as [x | x z1 z Hxz1 Hz1z].
      + exists y; split; [apply star_refl | eapply star_step; eauto].
      + destruct (Hlc x y1 z1 Hxy1 Hxz1) as [u [Hy1u Hz1u]].
        destruct (IH y1 Hxy1 y u Hy1y Hy1u) as [v [Hyv Huv]].
        destruct (IH z1 Hxz1 v z (star_trans _ _ _ Hz1u Huv) Hz1z) as [w [Hvw Hzw]].
        exists w; split; [eapply star_trans; eauto | exact Hzw].
  Qed.

  Lemma star_from_normal : forall x y, normal x -> star x y -> x = y.
  Proof.
    intros x y Hn H; destruct H as [x | x y' z Hxy _]; [reflexivity | exfalso; exact (Hn y' Hxy)].
  Qed.

  Theorem unique_normal_forms :
    confluent -> forall x y z, star x y -> star x z -> normal y -> normal z -> y = z.
  Proof.
    intros Hc x y z Hy Hz Hny Hnz.
    destruct (Hc x y z Hy Hz) as [w [Hyw Hzw]].
    rewrite (star_from_normal y w Hny Hyw), (star_from_normal z w Hnz Hzw); reflexivity.
  Qed.
End Abstract.

Arguments star {A} R _ _.
Arguments joinable {A} R _ _.
Arguments confluent {A} R.
Arguments normal {A} R _.

Section Strings.
  Variable S : Type.
  (* the defining relations of the presentation *)
  Variable E : list S -> list S -> Prop.

  (* the congruence on list Ss generated by E (the Thue congruence) *)
  Inductive cong : list S -> list S -> Prop :=
  | cong_base : forall x l r y, E l r -> cong (x ++ l ++ y) (x ++ r ++ y)
  | cong_refl : forall u, cong u u
  | cong_sym : forall u v, cong u v -> cong v u
  | cong_trans : forall u v w, cong u v -> cong v w -> cong u w.

  Lemma cong_context : forall x y u v, cong u v -> cong (x ++ u ++ y) (x ++ v ++ y).
  Proof.
    intros x y u v H; induction H.
    - replace (x ++ (x0 ++ l ++ y0) ++ y) with ((x ++ x0) ++ l ++ (y0 ++ y)) by (rewrite !app_assoc; reflexivity).
      replace (x ++ (x0 ++ r ++ y0) ++ y) with ((x ++ x0) ++ r ++ (y0 ++ y)) by (rewrite !app_assoc; reflexivity).
      apply cong_base; assumption.
    - apply cong_refl.
    - apply cong_sym; assumption.
    - eapply cong_trans; eauto.
  Qed.

  (* a rule set: a predicate on (lhs, rhs) pairs; one rewrite step *)
  Definition step (rules : list S -> list S -> Prop) (u v : list S) : Prop :=
    exists x l r y, rules l r /\ u = x ++ l ++ y /\ v = x ++ r ++ y.
  Definition sound (rules : list S -> list S -> Prop) : Prop := forall l r, rules l r -> cong l r.

  Theorem step_sound : forall rules u v, sound rules -> step rules u v -> cong u v.
  Proof.
    intros rules u v Hs [x [l [r [y [Hr [Hu Hv]]]]]]; subst.
    apply cong_context, Hs, Hr.
  Qed.

  Theorem star_sound : forall rules u v, sound rules -> star (step rules) u v -> cong u v.
  Proof.
    intros rules u v Hs H; induction H.
    - apply cong_refl.
    - eapply cong_trans; [eapply step_sound; eauto | exact IHstar].
  Qed.

  (* 'equal answers: two list Ss with a common reduct are congruent *)
  Corollary joinable_sound : forall rules u v, sound rules -> joinable (step rules) u v -> cong u v.
  Proof.
    intros rules u v Hs [w [Hu Hv]].
    eapply cong_trans; [eapply star_sound; eauto | apply cong_sym; eapply star_sound; eauto].
  Qed.

  (* Completion. A state is a rule set and a set of pending equations, both
     predicates; one completion move changes them as Knuth-Bendix does. *)
  Definition state := ((list S -> list S -> Prop) * (list S -> list S -> Prop))%type.
  Definition add (P : list S -> list S -> Prop) (a b : list S) : list S -> list S -> Prop :=
    fun l r => P l r \/ (l = a /\ r = b).

  Inductive move : state -> state -> Prop :=
  (* orient an equation u = v after reducing both sides to u', v' *)
  | move_orient : forall rules eqs u v u' v',
      eqs u v -> star (step rules) u u' -> star (step rules) v v' ->
      move (rules, eqs) (add rules u' v', eqs)
  (* add a critical pair: a list S w with one-step reducts p and q *)
  | move_critical : forall rules eqs w p q,
      step rules w p -> step rules w q -> move (rules, eqs) (rules, add eqs p q)
  (* simplify the right-hand side of a rule l -> r to r' *)
  | move_simplify : forall rules eqs l r r',
      rules l r -> star (step rules) r r' -> move (rules, eqs) (add rules l r', eqs)
  (* drop rules or equations (inter-reduction removes a rule after it was
     returned to the pending equations, and joined equations are dropped) *)
  | move_drop : forall rules eqs rules' eqs',
      (forall l r, rules' l r -> rules l r) -> (forall u v, eqs' u v -> eqs u v) ->
      move (rules, eqs) (rules', eqs')
  (* return a rule to the pending equations *)
  | move_return : forall rules eqs l r, rules l r -> move (rules, eqs) (rules, add eqs l r).

  Definition state_sound (s : state) : Prop :=
    sound (fst s) /\ (forall u v, snd s u v -> cong u v).

  Lemma move_sound : forall s s', move s s' -> state_sound s -> state_sound s'.
  Proof.
    intros s s' Hm [Hr He]; destruct Hm as
      [rules eqs u v u' v' Huv Hu Hv | rules eqs w p q Hp Hq | rules eqs l0 r0 r' Hlr Hr' | rules eqs rules' eqs' Hsub Hesub | rules eqs l0 r0 Hlr];
      simpl in *; split.
    - intros l r [Hx | [-> ->]]; [apply Hr; exact Hx |].
      apply cong_trans with u; [apply cong_sym; apply (star_sound rules); assumption |].
      apply cong_trans with v; [apply He; assumption | apply (star_sound rules); assumption].
    - exact He.
    - exact Hr.
    - intros a b [Hx | [-> ->]]; [apply He; exact Hx |].
      apply cong_trans with w; [apply cong_sym; apply (step_sound rules); assumption | apply (step_sound rules); assumption].
    - intros l r [Hx | [-> ->]]; [apply Hr; exact Hx |].
      apply cong_trans with r0; [apply Hr; assumption | apply (star_sound rules); assumption].
    - exact He.
    - intros l r Hx; apply Hr, Hsub, Hx.
    - intros a b Hx; apply He, Hesub, Hx.
    - exact Hr.
    - intros a b [Hx | [-> ->]]; [apply He; exact Hx | apply Hr; assumption].
  Qed.

  (* the initial state (no rules, the relations pending) is sound, and so is
     every state completion reaches from it *)
  Theorem completion_sound : forall s s',
      state_sound s -> clos_refl_trans _ move s s' -> state_sound s'.
  Proof.
    intros s s' Hs H; induction H; eauto using move_sound.
  Qed.

  Lemma initial_sound : state_sound ((fun _ _ => False), E).
  Proof.
    split; [intros l r [] |].
    intros u v H; simpl in H.
    replace u with ([] ++ u ++ []) by (rewrite app_nil_r; reflexivity).
    replace v with ([] ++ v ++ []) by (rewrite app_nil_r; reflexivity).
    apply cong_base; exact H.
  Qed.

  (* rewriting inside a context *)
  Lemma step_context : forall rules x y u v, step rules u v -> step rules (x ++ u ++ y) (x ++ v ++ y).
  Proof.
    intros rules x y u v [x0 [l [r [y0 [Hr [-> ->]]]]]].
    exists (x ++ x0), l, r, (y0 ++ y); split; [exact Hr |]; split; rewrite !app_assoc; reflexivity.
  Qed.

  Lemma star_context : forall rules x y u v, star (step rules) u v -> star (step rules) (x ++ u ++ y) (x ++ v ++ y).
  Proof.
    intros rules x y u v H; induction H; [apply star_refl |].
    eapply star_step; [apply step_context; eassumption | exact IHstar].
  Qed.

  (* 'distinct answers. With a confluent rule set that joins every relation,
     congruent list Ss are joinable; with sound rules the converse holds too. *)
  Theorem congruent_joinable : forall rules,
      confluent (step rules) -> (forall l r, E l r -> joinable (step rules) l r) ->
      forall u v, cong u v -> joinable (step rules) u v.
  Proof.
    intros rules Hc HE u v H; induction H.
    - destruct (HE l r H) as [w [Hl Hr]].
      exists (x ++ w ++ y); split; apply star_context; assumption.
    - exists u; split; apply star_refl.
    - destruct IHcong as [w [H1 H2]]; exists w; split; assumption.
    - destruct IHcong1 as [a [Hua Hva]]; destruct IHcong2 as [b [Hvb Hwb]].
      destruct (Hc v a b Hva Hvb) as [c [Hac Hbc]].
      exists c; split; eapply star_trans; eauto.
  Qed.

  Theorem decide_by_normal_forms : forall rules,
      sound rules -> confluent (step rules) -> (forall l r, E l r -> joinable (step rules) l r) ->
      forall u v nu nv,
        star (step rules) u nu -> normal (step rules) nu ->
        star (step rules) v nv -> normal (step rules) nv ->
        (cong u v <-> nu = nv).
  Proof.
    intros rules Hs Hc HE u v nu nv Hu Hnu Hv Hnv; split.
    - intro H.
      destruct (congruent_joinable rules Hc HE u v H) as [w [Huw Hvw]].
      destruct (Hc u nu w Hu Huw) as [a [Hnua Hwa]].
      destruct (Hc v nv w Hv Hvw) as [b [Hnvb Hwb]].
      assert (Ea : nu = a) by exact (star_from_normal _ _ nu a Hnu Hnua).
      assert (Eb : nv = b) by exact (star_from_normal _ _ nv b Hnv Hnvb).
      subst a b.
      (* nu and nv are both normal reducts of w *)
      exact (unique_normal_forms _ (step rules) Hc w nu nv Hwa Hwb Hnu Hnv).
    - intros <-.
      apply cong_trans with nu; [apply (star_sound rules); assumption |].
      apply cong_sym; apply (star_sound rules); assumption.
  Qed.
End Strings.

