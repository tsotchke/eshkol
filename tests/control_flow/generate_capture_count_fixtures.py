def callback_fixture() -> str:
    out = [HEADER.format(title="Procedures called by the runtime, capturing 0..66 variables.")]
    out.append("""
(require stdlib)

(define (parameter-with-converter convert) (make-parameter 1 convert))
""")
    for n in COUNTS:
        s = tri(n)
        t = total(n)
        out.append(f"""
;; ---- {n} captured variable(s) ----
(define (sites-{n})
  {let_open(n)}
    (let ((p (parameter-with-converter (lambda (x) (+ x {t})))))
      (list
        ;; guard clause body and reraise through a handler closure
        (guard (e (#t (+ e {t}))) (raise 1))
        (with-exception-handler
          (lambda (e) (+ e {t}))
          (lambda () (+ 1 (raise-continuable 1))))
        (call/cc (lambda (k) (with-exception-handler
                               (lambda (e) (k (+ e {t})))
                               (lambda () (raise 2)))))
        ;; parameter converter, at creation and under parameterize
        (p)
        (parameterize ((p 10)) (p))
        ;; multiple values
        (call-with-values (lambda () (values 1 {t})) (lambda (a b) (+ a b {t})))
        ;; call/cc receiver and apply
        (call/cc (lambda (k) (+ 1 {t})))
        (apply (lambda (a b) (+ a b {t})) (list 1 2))
        ;; list, vector and string traversals
        (map (lambda (x) (+ x {t})) (list 1 2))
        (let ((sum 0)) (for-each (lambda (x) (set! sum (+ sum x {t}))) (list 1 2)) sum)
        (filter (lambda (x) (> (+ x {t}) {s + 1})) (list 1 2 3))
        (fold-left (lambda (a x) (+ a x {t})) 0 (list 1 2))
        (vector-map (lambda (x) (+ x {t})) (vector 1 2))
        (let ((sum 0)) (vector-for-each (lambda (x) (set! sum (+ sum x {t}))) (vector 1 2)) sum)
        ;; comparator and predicate callbacks
        (sort (list 3 1 2) (lambda (a b) (< (+ a {t}) (+ b {t}))))
        (find (lambda (x) (> (+ x {t}) {s + 1})) (list 1 2 3))
        (any (lambda (x) (> (+ x {t}) {s + 2})) (list 1 2 3))
        (every (lambda (x) (> (+ x {t}) {s})) (list 1 2 3))
        (filter-map (lambda (x) (if (> x 1) (+ x {t}) #f)) (list 1 2 3))
        (fold (lambda (x a) (+ a x {t})) 0 (list 1 2))
        ;; promises
        (force (delay (+ 1 {t})))
        (force (make-promise (+ 2 {t})))))))
(test-case "runtime-called procedures with {n} captures"
           (list {1 + s} {2 + s} {2 + s}
                 {1 + s} {10 + s}
                 {1 + 2 * s}
                 {1 + s} {3 + s}
                 (list {1 + s} {2 + s}) {3 + 2 * s} (list 2 3) {3 + 2 * s}
                 (vector {1 + s} {2 + s}) {3 + 2 * s}
                 (list 1 2 3) 2 #t #t (list {2 + s} {3 + s}) {3 + 2 * s}
                 {1 + s} {2 + s})
           (sites-{n}))
""")
    out.append(FOOTER.format(tag="runtime-called procedure capture counts"))
    return "".join(out)


def parallel_fixture() -> str:
    out = [HEADER.format(title="Thread, coroutine, parallel and string-traversal entry procedures capturing 0..66 variables.")]
    out.append("""
(require stdlib)
(require core.threads)
""")
    for n in COUNTS:
        s = tri(n)
        t = total(n)
        out.append(f"""
(define (par-{n})
  {let_open(n)}
    (list
      (parallel-map (lambda (x) (+ x {t})) (list 1 2 3))
      (parallel-fold (lambda (a x) (+ a x {t})) 0 (list 1 2))
      (parallel-filter (lambda (x) (> (+ x {t}) {s + 1})) (list 1 2 3))
      (parallel-execute (lambda () (+ 1 {t})) (lambda () (+ 2 {t})))
      (thread-join (make-thread (lambda () (+ 4 {t}))))
      (coroutine-resume (make-coroutine (lambda () (+ 5 {t}))))
      (let ((sum 0)) (string-for-each (lambda (c) (set! sum (+ sum 1 {t}))) "ab") sum)
      (derivative (lambda (x) (* x (+ 2.0 {t}))) 3.0)
      (reduce (lambda (a x) (+ a x {t})) 0 (list 1 2))
      (remove (lambda (x) (> (+ x {t}) {s + 1})) (list 1 2 3)))))
(test-case "native entry procedures with {n} captures"
           (list (list {1 + s} {2 + s} {3 + s}) {3 + 2 * s} (list 2 3)
                 (list {1 + s} {2 + s}) {4 + s} {5 + s} {2 + 2 * s}
                 {float(2 + s)} {3 + 2 * s} (list 1))
           (par-{n}))
""")
    out.append(FOOTER.format(tag="native entry capture counts"))
    return "".join(out)


def arity_fixture() -> str:
    out = [HEADER.format(title="The call protocol for procedures capturing 0..66 variables.")]
    out.append("""
;; The callee reaches each call site as a value, so the argument count is
;; checked by the call protocol when the call is made.
(define (call-with-1 f) (f 1))
(define (call-with-2 f) (f 1 2))
(define (call-with-3 f) (f 1 2 3))
(define (call-with-5 f) (f 1 2 3 4 5))
(define (outcome thunk)
  (guard (e (#t (if (error-object? e)
                    (list 'error (error-object-message e))
                    (list 'raised e))))
    (thunk)))
""")
    for n in COUNTS:
        s = tri(n)
        t = total(n)
        out.append(f"""
;; ---- {n} captured variable(s) ----
(define (make-fixed-{n})
  {let_open(n)}
    (lambda (a b) (+ a b {t}))))
(define (make-variadic-{n})
  {let_open(n)}
    (lambda (a b . rest) (+ a b (length rest) {t}))))
(define fixed-{n} (make-fixed-{n}))
(define variadic-{n} (make-variadic-{n}))
(test-case "{n} captures, fixed arity, exact argument count" {3 + s}
           (outcome (lambda () (call-with-2 fixed-{n}))))
(test-case "{n} captures, fixed arity, too few arguments"
           (list 'error "Arity mismatch: <procedure> expects 2 arguments but got 1")
           (outcome (lambda () (call-with-1 fixed-{n}))))
(test-case "{n} captures, fixed arity, too many arguments"
           (list 'error "Arity mismatch: <procedure> expects 2 arguments but got 3")
           (outcome (lambda () (call-with-3 fixed-{n}))))
(test-case "{n} captures, variadic, fewer than the fixed parameters"
           (list 'error "Arity mismatch: <procedure> expects at least 2 arguments but got 1")
           (outcome (lambda () (call-with-1 variadic-{n}))))
(test-case "{n} captures, variadic, exactly the fixed parameters" {3 + s}
           (outcome (lambda () (call-with-2 variadic-{n}))))
(test-case "{n} captures, variadic, one rest argument" {4 + s}
           (outcome (lambda () (call-with-3 variadic-{n}))))
(test-case "{n} captures, variadic, three rest arguments" {6 + s}
           (outcome (lambda () (call-with-5 variadic-{n}))))
(test-case "{n} captures, still callable after the refused calls" {3 + s}
           (outcome (lambda () (call-with-2 fixed-{n}))))
""")
    out.append(FOOTER.format(tag="closure call protocol capture counts"))
    return "".join(out)


FIXTURES = {
    "tests/control_flow/dynamic_wind_capture_counts.esk": wind_fixture,
    "tests/closures/runtime_called_capture_counts.esk": callback_fixture,
    "tests/parallel/native_entry_capture_counts.esk": parallel_fixture,
    "tests/closures/call_protocol_capture_counts.esk": arity_fixture,
}


def main() -> int:
    check = "--check" in sys.argv[1:]
    stale = 0
    for rel, make in FIXTURES.items():
        path = ROOT / rel
        text = make()
        if check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                print(f"STALE: {rel}")
                stale += 1
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
            print(f"wrote {rel}")
    return 1 if stale else 0


if __name__ == "__main__":
    raise SystemExit(main())
