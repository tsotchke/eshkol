#!/usr/bin/env python3
"""Generate the capture-count fixtures for procedures called by the runtime.

Every procedure the language calls on the program's behalf -- dynamic-wind
before/after thunks run during a non-local exit or a re-entry, exception
handlers, parameter converters, multiple-value producers and consumers,
higher-order list, vector and string callbacks, sort comparators, promise
bodies, thread, coroutine and parallel entry procedures -- is entered through the same closure-call protocol as an
ordinary call, so the number of variables it captures is never observable.
The fixtures exercise each of those call sites with closures capturing
0, 1, 4, 5, 8, 17, 64, 65 and 66 variables and check the exact value each one
computes. A closure call passes the addresses of the first 64 capture slots:
64 is the largest count whose procedure body is entered directly, and 65 and
66 are the first two entered through an entry function that receives the
address of slot 0 and forwards every slot address to the body.

A fourth fixture checks the call protocol itself at those counts: a procedure
called with too few or too many arguments, and a variadic procedure called
with fewer than its fixed parameters, raises the same catchable arity error
whatever it captures.

Usage: generate_capture_count_fixtures.py [--check]
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
COUNTS = (0, 1, 4, 5, 8, 17, 64, 65, 66)

HEADER = """;; GENERATED by tests/control_flow/generate_capture_count_fixtures.py -- do not edit.
;; {title}

(define tests-passed 0)
(define tests-failed 0)

(define (test-case name expected actual)
  (if (equal? expected actual)
      (begin
        (set! tests-passed (+ tests-passed 1))
        (display "PASS: ") (display name) (newline))
      (begin
        (set! tests-failed (+ tests-failed 1))
        (display "FAIL: ") (display name)
        (display " (expected ") (display expected)
        (display ", got ") (display actual) (display ")") (newline))))
"""

FOOTER = """
(newline)
(display "{tag} passed: ") (display tests-passed) (newline)
(display "{tag} failed: ") (display tests-failed) (newline)
(if (= tests-failed 0)
    (begin (display "{tag}: ALL PASS") (newline))
    (begin (display "{tag}: FAILURES") (newline) (exit 1)))
"""


def names(n: int) -> list[str]:
    return [f"v{i}" for i in range(1, n + 1)]


def bindings(n: int) -> str:
    return " ".join(f"(v{i} {i})" for i in range(1, n + 1))


def total(n: int) -> str:
    """An expression reading every one of the n captured variables."""
    return "(+ 0 " + " ".join(names(n)) + ")" if n else "0"


def tri(n: int) -> int:
    return n * (n + 1) // 2


def let_open(n: int) -> str:
    return f"(let ({bindings(n)})"


# --------------------------------------------------------------------------
# dynamic-wind
# --------------------------------------------------------------------------

def wind_fixture() -> str:
    out = [HEADER.format(title="dynamic-wind thunks capturing 0..66 variables on every exit path.")]
    out.append("""
(define acc 0)
(define trace '())
(define (note x) (set! trace (cons x trace)))
(define saved-k #f)
(define reentries 0)
(define (top-level-after) (set! acc (+ acc 5)))
""")
    for n in COUNTS:
        s = tri(n)
        bump = f"(set! v{n} (+ v{n} 100))" if n else "#t"
        bumped = s + (100 if n else 0)
        # mode 0: normal return; 1: escape through a continuation; 2: raise.
        out.append(f"""
;; ---- {n} captured variable(s) ----
(define (wind-{n} mode)
  {let_open(n)}
    (let ((r (guard (e (#t (list 'raised e)))
               (call/cc
                 (lambda (k)
                   (dynamic-wind
                     (lambda () (set! acc (+ acc 1 {total(n)})))
                     (lambda ()
                       (cond ((= mode 0) 'returned)
                             ((= mode 1) (k 'escaped))
                             (else (raise 'boom))))
                     (lambda ()
                       {bump}
                       (set! acc (+ acc (* 1000 (+ 5 {total(n)})))))))))))
      (list r {total(n)}))))
""")
        per_call = 1 + s + 1000 * (5 + bumped)
        for mode, label, r in ((0, "normal return", "'returned"),
                               (1, "continuation escape", "'escaped"),
                               (2, "raise", "(list 'raised 'boom)")):
            out.append(f"""(set! acc 0)
(test-case "wind {n} captures, {label}: value and mutated capture" (list {r} {bumped}) (wind-{n} {mode}))
(test-case "wind {n} captures, {label}: before and after each ran once" {per_call} acc)
""")
        # A variadic after thunk and a named top-level procedure as after thunk.
        out.append(f"""
(define (wind-rest-{n})
  {let_open(n)}
    (call/cc
      (lambda (k)
        (dynamic-wind
          (lambda rest (set! acc (+ acc 1 (length rest) {total(n)})))
          (lambda () (k 'escaped))
          (lambda rest (set! acc (+ acc (* 1000 (+ 5 (length rest) {total(n)}))))))))))
(set! acc 0)
(test-case "wind {n} captures, variadic thunks, continuation escape" 'escaped (wind-rest-{n}))
(test-case "wind {n} captures, variadic thunks ran with no arguments" {1 + s + 1000 * (5 + s)} acc)

(define (wind-reenter-{n})
  {let_open(n)}
    (set! reentries 0)
    (set! saved-k #f)
    (dynamic-wind
      (lambda () (set! acc (+ acc 1 {total(n)})))
      (lambda () (call/cc (lambda (k) (set! saved-k k))) 'body)
      (lambda () (set! acc (+ acc (* 1000 (+ 5 {total(n)}))))))
    (if (< reentries 2)
        (begin (set! reentries (+ reentries 1)) (saved-k 'again))
        {total(n)})))
(set! acc 0)
(test-case "wind {n} captures, re-entry: captures intact" {s} (wind-reenter-{n}))
(test-case "wind {n} captures, re-entry: before and after ran three times" {3 * (1 + s + 1000 * (5 + s))} acc)
""")

    # Nested extents with different capture counts, left by one transfer.
    for outer, inner in ((5, 17), (17, 5), (65, 8), (4, 65), (64, 66)):
        so, si = tri(outer), tri(inner)
        inner_names = " ".join(f"w{i}" for i in range(1, inner + 1))
        inner_bind = " ".join(f"(w{i} {i})" for i in range(1, inner + 1))
        inner_total = f"(+ 0 {inner_names})"
        for kind, leave in (("continuation", "(k 'out)"), ("raise", "(raise 'out)")):
            fn = f"nested-{outer}-{inner}-{kind}"
            out.append(f"""
(define ({fn})
  {let_open(outer)}
    (guard (e (#t e))
      (call/cc
        (lambda (k)
          (dynamic-wind
            (lambda () (note (list 'in-outer {total(outer)})))
            (lambda ()
              (let ({inner_bind})
                (dynamic-wind
                  (lambda () (note (list 'in-inner {inner_total})))
                  (lambda () {leave})
                  (lambda () (note (list 'out-inner {inner_total} {total(outer)}))))))
            (lambda () (note (list 'out-outer {total(outer)})))))))))
(set! trace '())
(test-case "nested wind {outer} around {inner}, {kind}: value" 'out ({fn}))
(test-case "nested wind {outer} around {inner}, {kind}: order and captures"
           '((in-outer {so}) (in-inner {si}) (out-inner {si} {so}) (out-outer {so}))
           (reverse trace))
""")

    out.append("""
;; A named top-level procedure as the exit thunk.
(set! acc 0)
(test-case "wind with a top-level procedure as after thunk, escape" 'gone
           (call/cc (lambda (k) (dynamic-wind (lambda () #t) (lambda () (k 'gone)) top-level-after))))
(test-case "top-level after thunk ran once" 5 acc)
""")
    out.append(FOOTER.format(tag="dynamic-wind capture counts"))
    return "".join(out)


